async (page) => {
  await page.waitForFunction(()=>window.__NEON_NEXT__);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1600,height:1000});
  await page.bringToFront();
  const read=()=>page.evaluate(()=>window.__NEON_NEXT__.snapshot());
  if((await read()).mode!=='construction')await page.getByRole('button',{name:/Visit the workshop/}).click();
  const ledger=page.getByText('Workshop ledger',{exact:true});
  await ledger.click();await page.getByRole('button',{name:'Reset all defenses & crowns'}).click();await ledger.click();
  await page.getByRole('button',{name:/2 CAPACITY Royal Ballista/}).click();
  await page.getByRole('button',{name:'Inspect machine',exact:true}).click();
  if(!(await read()).preview.compare)await page.getByRole('button',{name:'Compare all three ranks'}).click();
  await page.screenshot({path:'output/playwright/construction-ballista-ranks.png'});
  await page.getByRole('button',{name:/1 CAPACITY Aegis Projector/}).click();
  await page.screenshot({path:'output/playwright/construction-aegis-ranks.png'});
  await page.getByRole('button',{name:'Show selected rank'}).click();
  await page.getByRole('button',{name:/2 CAPACITY Royal Ballista/}).click();
  await page.getByRole('button',{name:'Build rank I · 100 crowns',exact:true}).click();
  await page.getByRole('button',{name:'Upgrade to II · 160 crowns',exact:true}).click();
  await page.getByRole('button',{name:'Upgrade to III · 240 crowns',exact:true}).click();
  if((await read()).plan.gold!==700)throw new Error('Incorrect tier investment');
  await page.getByRole('button',{name:'Relocate · free',exact:true}).click();
  await page.getByRole('button',{name:'East watch Open site',exact:true}).click();
  await page.getByRole('button',{name:'Confirm relocation · free',exact:true}).click();
  let s=await read();
  if(s.plan.buildings[0].site!=='east-watch'||s.plan.gold!==700)throw new Error('Relocation cost or identity changed');
  await page.getByRole('button',{name:'West courtyard Open site',exact:true}).click();
  await page.getByRole('button',{name:/1 CAPACITY Aegis Projector/}).click();
  await page.getByRole('button',{name:'III Bastion engine',exact:true}).click();
  await page.getByRole('button',{name:'Build rank III · 550 crowns',exact:true}).click();
  s=await read();
  if(s.plan.gold!==150||s.plan.buildings.length!==2)throw new Error('Aegis purchase incorrect');
  if(!await page.getByRole('button',{name:'Build rank III · 550 crowns',exact:true}).isDisabled())throw new Error('Occupied site can be rebuilt');
  await page.screenshot({path:'output/playwright/construction-placement.png'});
  const plan=s.plan;
  await page.reload();await page.getByRole('button',{name:/Visit the workshop/}).click();
  if(JSON.stringify((await read()).plan, Object.keys({...plan,...plan.buildings[0]}).sort())!==JSON.stringify(plan, Object.keys({...plan,...plan.buildings[0]}).sort()))throw new Error('Workshop reload did not retain the plan');
  await page.getByRole('button',{name:'Enter courtyard ↗',exact:true}).click();
  await page.waitForFunction(()=>window.__NEON_NEXT__.snapshot().structureHits>0,{},{timeout:12000});
  let combat=await read();
  if(combat.hits||combat.shots||combat.defenses.length!==2)throw new Error('Defense shots contaminated commander statistics');
  await page.keyboard.down('KeyW');await page.waitForTimeout(1250);await page.keyboard.up('KeyW');
  await page.keyboard.down('KeyA');await page.waitForTimeout(750);await page.keyboard.up('KeyA');
  const position=(await read()).player;
  if(Math.hypot(position.x+3,position.z)>.7)throw new Error('Could not reach shield drill through real movement: '+JSON.stringify(position));
  await page.getByRole('button',{name:'Start ward trial',exact:true}).click();
  await page.waitForFunction(()=>window.__NEON_NEXT__.snapshot().blockedDamage>0,{},{timeout:16000});
  combat=await read();
  await page.screenshot({path:'output/playwright/construction-shield.png'});
  await page.getByRole('button',{name:'End ward trial',exact:true}).click();
  await page.getByRole('button',{name:'Workshop',exact:true}).click();
  if((await read()).plan.gold!==150)throw new Error('Courtyard changed construction funds');
  if(errors.length)throw new Error(JSON.stringify(errors));
  return {plan,combat:{structureHits:combat.structureHits,blockedDamage:combat.blockedDamage,playerHP:combat.player.hp,defenses:combat.defenses},errors};
}
