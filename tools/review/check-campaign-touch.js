async(page)=>{
 const errors=[],failed=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)failed.push(r.url());});
 await page.evaluate(()=>localStorage.removeItem('neon-knights:v3:campaign:2'));await page.reload();
 await page.getByRole('button',{name:'Build',exact:true}).waitFor();
 if(await page.evaluate(()=>typeof window.__castle!=='undefined'))throw Error('Development hook in production');
 if(!await page.getByRole('heading',{name:/Level 1 \/ 15/}).count())throw Error('Wrong campaign version');
 if(await page.locator('[data-pick="forge"]').isEnabled())throw Error('Forge unlocked early');
 await page.locator('[data-pick="tavern"]').tap();await page.locator('.council-content [data-action="slot:inner-sw"]').tap();
 await page.getByRole('button',{name:'Knights',exact:true}).tap();await page.locator('[data-action="recruit:elin"]').tap();
 const initial=await page.evaluate(()=>JSON.parse(localStorage.getItem('neon-knights:v3:campaign:2')));
 if(initial.knights.length!==2||initial.buildings[0].kind!=='tavern')throw Error('Touch build/recruit failed');
 await page.screenshot({path:'output/playwright/campaign-touch-company.png'});
 await page.getByRole('button',{name:/^Begin watch/}).tap();await page.waitForTimeout(1800);
 await page.locator('#king-guard').tap();await page.waitForTimeout(80);
 if(!/GUARDING|PERFECT|[0-9]/.test(await page.locator('#guard-status').innerText()))throw Error('Touch guard failed');
 await page.screenshot({path:'output/playwright/campaign-touch-battle.png'});
 await page.getByRole('button',{name:'Pause',exact:true}).tap();
 if(!await page.getByRole('button',{name:'Resume the watch',exact:true}).isVisible())throw Error('Touch pause failed');
 // CHECKPOINT: generated by the complete legal simulation, not a live-game mutation hook.
 const checkpoint=window.__REPLACE_CHECKPOINT__;
 await page.evaluate(s=>localStorage.setItem('neon-knights:v3:campaign:2',JSON.stringify(s)),checkpoint);
 await page.reload();await page.getByRole('button',{name:'Build',exact:true}).waitFor();
 await page.locator('[data-pick="war-room"]').tap();await page.locator('.council-content [data-action="slot:inner-nw"]').tap();
 const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('neon-knights:v3:campaign:2')));
 if(!state.buildings.some(b=>b.kind==='war-room'))throw Error('New War Room did not build');
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw Error('Horizontal overflow');
 await page.screenshot({path:'output/playwright/campaign-touch-new-wings.png'});
 await page.reload();await page.getByRole('button',{name:'Build',exact:true}).waitFor();
 if(errors.length||failed.length)throw Error(JSON.stringify({errors,failed}));
 return {production:true,viewport:page.viewportSize(),openingTavern:true,recruitedElin:true,guard:true,pause:true,warRoom:true,checkpoint:state.encounter,overflow,errors,failed};
}
