async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const snap = () => page.evaluate(() => window.__castle.snapshot());
  await page.evaluate(() => localStorage.removeItem('neon-knights:v3:castle:1'));
  await page.reload();
  await page.getByRole('button',{name:'Place Storm Spire for 140 crowns',exact:true}).waitFor();
  const card = await page.getByRole('button',{name:'Place Storm Spire for 140 crowns',exact:true}).boundingBox();
  await page.mouse.move(card.x+card.width/2,card.y+card.height/2);await page.mouse.down();
  const target = await page.getByRole('button',{name:'Place on North platform',exact:true}).boundingBox();
  await page.mouse.move(target.x+target.width/2,target.y+target.height/2,{steps:20});
  await page.screenshot({path:'output/playwright/circular-placement.png'});
  await page.mouse.up();
  let s=await snap(); assert(s.state.buildings.length===1 && s.state.buildings[0].site==='west-watch','Drag must place on North');assert(s.state.gold===510,'Drag cost exactly once');
  await page.getByRole('button',{name:'Move for free',exact:true}).click();
  await page.getByRole('button',{name:'East platform',exact:true}).click();
  s=await snap();assert(s.state.buildings[0].site==='east-watch' && s.state.gold===510,'Free relocation preserves ledger');
  await page.getByRole('button',{name:'Place Dawn Sanctuary for 110 crowns',exact:true}).click();
  await page.keyboard.press('Escape');
  assert((await snap()).state.gold===510,'Cancel must not spend crowns');
  await page.getByRole('button',{name:'Place Dawn Sanctuary for 110 crowns',exact:true}).click();
  await page.getByRole('button',{name:'South platform',exact:true}).click();
  assert((await snap()).state.buildings.length===2,'Tap to place');
  await page.getByRole('button',{name:'Knights',exact:true}).click();
  await page.locator('[data-action="talent:aldren:slam"]').click();
  assert((await snap()).state.knights[0].talents.includes('slam'),'Learn talent');
  assert(await page.locator('[data-action="talent:aldren:aftershock"]').getAttribute('aria-disabled')==='true','Unavailable talent is disabled');
  assert((await snap()).state.knights[0].talents.length===1,'Reject talent without a point');
  await page.getByRole('button',{name:'Reset free',exact:true}).click();
  await page.locator('[data-action="talent:aldren:taunt"]').click();
  await page.locator('[data-action="knight:elin"]').click();
  await page.locator('[data-action="talent:elin:mending"]').click();
  await page.screenshot({path:'output/playwright/circular-talents.png'});
  await page.reload();await page.getByRole('button',{name:'Begin watch',exact:false}).waitFor();
  s=await snap();assert(s.state.knights[0].talents[0]==='taunt','Talents survive reload');
  await page.getByRole('button',{name:'Begin watch',exact:false}).click();
  const canvas=await page.locator('.castle-canvas canvas').boundingBox();
  const before=await snap();
  await page.mouse.move(canvas.x+canvas.width*.85,canvas.y+canvas.height*.5,{steps:12});
  await page.waitForTimeout(1200);
  const east=await snap();assert(east.king.x>4,'Mouse hover moves east without any button');assert(Math.abs(Math.hypot(east.king.x,east.king.z)-5.3)<.001,'King stays on circle');
  await page.mouse.move(canvas.x+canvas.width*.15,canvas.y+canvas.height*.5,{steps:20});
  await page.waitForTimeout(1900);const west=await snap();assert(west.king.x< -4,'Mouse hover moves west');
  await page.mouse.down();await page.waitForTimeout(1900);assert((await snap()).king.hp>0 && (await snap()).time>before.time,'Battle progresses');
  await page.screenshot({path:'output/playwright/circular-charge.png'});await page.mouse.up();
  await page.keyboard.press('Escape');const paused=await snap();await page.waitForTimeout(300);assert((await snap()).time===paused.time,'Pause freezes simulation');
  return {placement:'drag, tap, relocation, cancellation passed',talents:'learn, reject, reset, persistence passed',mouse:'hover east/west and charge passed',state:s.state};
}
